// Єдина точка доступу до БД. Двигун обирається змінною CRM_DATABASE_URL:
// є вона — Postgres, немає — SQLite. Решта коду різниці не бачить.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const driver = process.env.CRM_DATABASE_URL
  ? await import('./db-pg.js')
  : await import('./db-sqlite.js');

export const { engine, location, exec, all, get, run, close } = driver;
export const dbFile = location;
export const isPostgres = engine === 'postgres';

// Таблиці, де первинний ключ не «id» — їм не можна дописувати RETURNING id.
const NO_ID = new Set(['sessions', 'settings', 'roles']);

export async function insert(table, data) {
  const keys = Object.keys(data);
  if (!keys.length) throw new Error('empty insert');
  const values = keys.map((k) => data[k]);
  const placeholders = keys.map(() => '?').join(',');
  const returning = isPostgres && !NO_ID.has(table) ? ' RETURNING id' : '';
  const res = await run(`INSERT INTO ${table} (${keys.join(',')}) VALUES (${placeholders})${returning}`, ...values);
  return res.lastInsertRowid == null ? null : Number(res.lastInsertRowid);
}

export async function update(table, id, data) {
  const keys = Object.keys(data);
  if (!keys.length) return 0;
  const res = await run(
    `UPDATE ${table} SET ${keys.map((k) => `${k}=?`).join(',')} WHERE id=?`,
    ...keys.map((k) => data[k]), id,
  );
  return res.changes;
}

export async function remove(table, id) {
  return (await run(`DELETE FROM ${table} WHERE id=?`, id)).changes;
}

export async function audit({ user_id = null, action, entity = null, entity_id = null, payload = null, ip = null }) {
  await insert('audit_log', {
    user_id, action, entity, entity_id,
    payload: payload ? JSON.stringify(payload).slice(0, 4000) : null,
    ip,
  });
}

export async function setting(key, value) {
  if (value === undefined) return (await get('SELECT value FROM settings WHERE key=?', key))?.value ?? null;
  await run(
    'INSERT INTO settings (key,value) VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',
    key, String(value),
  );
  return value;
}

// DDL пишеться один раз діалектом SQLite; для Postgres переписуємо типи —
// так схема лишається єдиним джерелом істини.
export function toPostgresDdl(sql) {
  return sql
    .split('\n')
    .filter((line) => !/^\s*PRAGMA/i.test(line))
    .join('\n')
    .replace(/\bINTEGER PRIMARY KEY\b/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bREAL\b/g, 'double precision');
}

export async function initSchema() {
  const sql = fs.readFileSync(path.join(here, 'schema.sql'), 'utf8');
  await exec(isPostgres ? toPostgresDdl(sql) : sql);
  return { engine, location };
}
